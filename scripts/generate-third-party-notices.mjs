import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const packages = new Map();

function packageName(path) {
  const marker = "node_modules/";
  const index = path.lastIndexOf(marker);
  return index < 0 ? "" : path.slice(index + marker.length);
}

function add(name, version, license, source) {
  if (!name || !version) return;
  const normalized = String(license || "UNKNOWN").trim() || "UNKNOWN";
  packages.set(`${name}@${version} (${source})`, {
    name,
    version,
    license: normalized,
    source,
  });
}

for (const component of ["desktop", "portal"]) {
  const lock = JSON.parse(
    readFileSync(resolve(root, component, "package-lock.json"), "utf8"),
  );
  for (const [path, metadata] of Object.entries(lock.packages ?? {})) {
    if (!path || !metadata || typeof metadata !== "object") continue;
    add(packageName(path), metadata.version, metadata.license, `npm:${component}`);
  }
}

const cargo = JSON.parse(
  execFileSync(
    "cargo",
    [
      "metadata",
      "--format-version",
      "1",
      "--filter-platform",
      "aarch64-apple-darwin",
      "--manifest-path",
      resolve(root, "desktop", "src-tauri", "Cargo.toml"),
    ],
    { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  ),
);
for (const metadata of cargo.packages ?? []) {
  if (!metadata.source && metadata.name === "spaces") continue;
  add(metadata.name, metadata.version, metadata.license, "cargo:desktop");
}

const rows = [...packages.values()].sort(
  (a, b) =>
    a.license.localeCompare(b.license) ||
    a.name.localeCompare(b.name) ||
    a.version.localeCompare(b.version) ||
    a.source.localeCompare(b.source),
);
const unknown = rows.filter((entry) => entry.license === "UNKNOWN");
const blocked = rows.filter((entry) =>
  /\b(AGPL|GPL|SSPL|BUSL)\b|Commons Clause/i.test(entry.license),
);

const byLicense = new Map();
for (const row of rows) {
  const group = byLicense.get(row.license) ?? [];
  group.push(row);
  byLicense.set(row.license, group);
}

const output = [
  "# Third-party notices",
  "",
  "Generated by `node scripts/generate-third-party-notices.mjs` from the locked",
  "npm and Cargo dependency metadata. Package authors retain all rights to their",
  "work; consult each package distribution for its complete license text.",
  "",
  `Inventory: ${rows.length} locked package records across ${byLicense.size} license expressions.`,
  "",
];
for (const [license, entries] of byLicense) {
  output.push(`## ${license}`, "");
  for (const entry of entries) {
    output.push(`- \`${entry.name}@${entry.version}\` — ${entry.source}`);
  }
  output.push("");
}
writeFileSync(resolve(root, "THIRD_PARTY_NOTICES.md"), `${output.join("\n").trimEnd()}\n`);

if (unknown.length || blocked.length) {
  const details = [...unknown, ...blocked]
    .map((entry) => `${entry.name}@${entry.version}: ${entry.license}`)
    .join("\n");
  throw new Error(`Dependency license review failed:\n${details}`);
}
